"""Independent oracle for BandLinkTests: writes every frame of one handshake + message scenario as hex.
Built from Gadgetbridge/AstroBox semantics with Python's hmac and `cryptography`, sharing no code with BandLink.

Run: python3 -I make_vectors.py > Vectors.swift
"""
import hashlib, hmac
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.ciphers.aead import AESCCM

AUTH_KEY = bytes.fromhex("00112233445566778899aabbccddeeff")  # test key, not a real band
PHONE_NONCE = bytes(range(0x00, 0x10))
WATCH_NONCE = bytes(range(0x20, 0x30))
APP = "com.maps4miband.band"
SHA = bytes.fromhex("515e6fbbaae846a3945ffb938f3694ee0b8d2639")
MESSAGE = b'{"i":"hello"}'


def varint(n):
    out = bytearray()
    while True:
        b = n & 0x7F; n >>= 7
        out.append(b | (0x80 if n else 0))
        if not n: return bytes(out)


def f(num, v):  # protobuf field: int -> varint, bytes/str -> length-delimited
    if isinstance(v, int): return varint(num << 3) + varint(v)
    if isinstance(v, str): v = v.encode()
    return varint(num << 3 | 2) + varint(len(v)) + v


def crc16_arc(data):
    crc = 0
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ 0xA001 if crc & 1 else crc >> 1
    return crc


def frame(ptype, seq, payload):
    return b"\xa5\xa5" + bytes([ptype, seq]) + len(payload).to_bytes(2, "little") + crc16_arc(payload).to_bytes(2, "little") + payload


def ctr(key, data):
    e = Cipher(algorithms.AES(key), modes.CTR(key)).encryptor()
    return e.update(data) + e.finalize()


h = lambda k, m: hmac.new(k, m, hashlib.sha256).digest()
prk = h(PHONE_NONCE + WATCH_NONCE, AUTH_KEY)
okm, t = b"", b""
for i in (1, 2, 3):
    t = h(prk, t + b"miwear-auth" + bytes([i])); okm += t
dec_key, enc_key, dec_nonce, enc_nonce = okm[0:16], okm[16:32], okm[32:36], okm[36:40]

assert crc16_arc(b"123456789") == 0xBB3D  # CRC-16/ARC check value
# Session config TLVs from Gadgetbridge (official app dump): version 1.0.0, max frame 0xfc00, tx window 32, timeout 10000 ms
session_tlv = bytes.fromhex("010300010000" "02020000fc" "0302002000" "0402001027")
cmd = lambda t, s, *fields: f(1, t) + f(2, s) + b"".join(fields)
ref = f(1, APP) + f(2, SHA)
plain = lambda seq, c: frame(3, seq, b"\x01\x01" + c)        # channel 1, opcode 1 (plaintext)
phone_enc = lambda seq, c: frame(3, seq, b"\x01\x02" + ctr(enc_key, c))
band_enc = lambda seq, c: frame(3, seq, b"\x01\x02" + ctr(dec_key, c))
ack = lambda seq: frame(1, seq, b"")

companion = f(1, 1) + f(3, "maps4miband") + f(4, 0xFFFFFFFF)
app_confirm = f(1, h(enc_key, PHONE_NONCE + WATCH_NONCE)) + f(2, AESCCM(enc_key, tag_length=4).encrypt(enc_nonce + bytes(8), companion, None))

v = {
    "sessionStart": frame(2, 0, b"\x01" + session_tlv),
    "bandSessionReply": frame(2, 0, b"\x02" + session_tlv),
    "authStep1": plain(0, cmd(1, 26, f(3, f(30, f(1, PHONE_NONCE))))),
    "bandVerify": plain(0, cmd(1, 26, f(3, f(31, f(1, WATCH_NONCE) + f(2, h(dec_key, WATCH_NONCE + PHONE_NONCE)))))),
    "bandVerifyWrongKey": plain(0, cmd(1, 26, f(3, f(31, f(1, WATCH_NONCE) + f(2, bytes(32)))))),
    "ack0": ack(0),
    "authStep2": plain(1, cmd(1, 27, f(3, f(32, app_confirm)))),
    "bandConfirm": plain(1, cmd(1, 27, f(3, f(33, f(1, 1))))),
    "ack1": ack(1),
    "listRequest": phone_enc(2, cmd(20, 0)),
    "bandList": band_enc(2, cmd(20, 0, f(22, f(1, f(1, f(1, "com.other.app") + f(2, bytes(20))) + f(1, ref + f(5, "Dẫn đường")))))),
    "bandListWithoutApp": band_enc(2, cmd(20, 0, f(22, f(1, f(1, f(1, "com.other.app") + f(2, bytes(20))))))),
    "ack2": ack(2),
    "launch": phone_enc(3, cmd(20, 4, f(22, f(6, f(1, ref) + f(2, APP))))),
    "bandAsksStatus": band_enc(3, cmd(20, 6, f(22, f(5, ref)))),
    "ack3": ack(3),
    "messageFrame": phone_enc(4, cmd(20, 8, f(22, f(9, f(1, ref) + f(2, MESSAGE))))),
    "sessionEnd": phone_enc(5, cmd(20, 7, f(22, f(8, f(1, ref) + f(2, 1))))),
    "secondMessageFrame": phone_enc(6, cmd(20, 8, f(22, f(9, f(1, ref) + f(2, MESSAGE))))),
}

print("// Generated by make_vectors.py. Do not edit.\nimport Foundation\n\nenum V {")
print(f'    static let authKey = "{AUTH_KEY.hex()}"\n    static let phoneNonce = hex("{PHONE_NONCE.hex()}")')
print(f'    static let app = "{APP}"\n    static let message = Data(#"{MESSAGE.decode()}"#.utf8)')
for k, b in v.items():
    print(f'    static let {k} = hex("{b.hex()}")')
print("}")
